#!/usr/bin/env python3
"""Compose profile/packages.x86_64 from the base list plus chosen components.

  scripts/gen-packages.py                       # preset "everything" (the owner's ISO)
  scripts/gen-packages.py --preset minimal      # base system only
  scripts/gen-packages.py --components steam,obsidian
  scripts/gen-packages.py --check               # exit 1 if the committed file is stale

The ISO is whatever this writes; components left out can still be installed later with
labyrinth-apps (needs network). Output has no trailing comments (mkarchiso's parser
leaves whitespace on them; see Chymaera_OS/CLAUDE.md).
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, "profile", "packages.base")
COMPONENTS = os.path.join(ROOT, "profile", "airootfs", "usr", "share", "labyrinth", "components.json")
OUT = os.path.join(ROOT, "profile", "packages.x86_64")
NAME = re.compile(r"^[a-z0-9@._+-]+$")


def read_base(path):
    pkgs = []
    for line in open(path, encoding="utf-8").read().splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        if "#" in s or not NAME.match(s):
            raise ValueError(f"{path}: bad package line {line!r} (comments must be on their own line)")
        pkgs.append(s)
    return pkgs


def compose(base_pkgs, data, ids):
    comps = {c["id"]: c for c in data["components"]}
    unknown = [i for i in ids if i not in comps]
    if unknown:
        raise KeyError(f"unknown component(s): {', '.join(unknown)}")
    lines = [
        "# GENERATED by scripts/gen-packages.py from profile/packages.base and the",
        "# components below. Edit those, not this file. Names unverified against CachyOS repos",
        "# unless noted in components.json.",
    ]
    seen = set()
    def add(name):
        if name in seen:
            return
        if not NAME.match(name):
            raise ValueError(f"bad package name {name!r}")
        seen.add(name)
        lines.append(name)
    for p in base_pkgs:
        add(p)
    for i in ids:
        c = comps[i]
        pk = list(c.get("packages", [])) + ([c["pkgbuild"]] if c.get("pkgbuild") else [])
        if pk:
            lines.append(f"# component: {i}")
            for p in pk:
                add(p)
    return "\n".join(lines) + "\n"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--preset", default=None)
    ap.add_argument("--components", default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    data = json.load(open(COMPONENTS, encoding="utf-8"))
    if a.components is not None:
        ids = [x for x in a.components.split(",") if x]
    else:
        preset = a.preset or "everything"
        if preset not in data["presets"]:
            print(f"unknown preset {preset!r}; have: {', '.join(data['presets'])}", file=sys.stderr)
            return 2
        ids = data["presets"][preset]
    text = compose(read_base(BASE), data, ids)
    if a.check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("profile/packages.x86_64 is stale; run scripts/gen-packages.py", file=sys.stderr)
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(seen_names(text))} packages, components: {', '.join(ids) or 'none'}")
    return 0


def seen_names(text):
    return [l for l in text.splitlines() if l and not l.startswith("#")]


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

#!/usr/bin/python3 -I
"""compare.py: scripts/publish-repo.py against labyrinth-publish-repo (this crate), on made-up worlds.

    cargo build --release && python3 -I parity/compare.py [--old FILE] [--new FILE] [--only CASE[,CASE]] [-v]

Everything runs inside a user, mount, PID and network namespace of its own (unshare -rmnpf): nothing reaches the network,
the world is a tmpfs mounted on /mnt inside the namespace (gone when the run ends), and Labyrinth's real keyring folder
(~/.local/share/labyrinth-signing) and gh's settings (~/.config/gh) are covered by empty folders, so neither program could
read them even by mistake. The signing key is a throw-away ed25519 key made for the run (no passphrase, in the world's own
GNUPGHOME); standin.py swaps Labyrinth's fingerprint for it and fixes gpg's clock, so both programs make byte-identical
signatures. git, gh, makepkg and build-local-packages.sh are stand-ins (standin.py); bsdtar, gzip, vercmp, gpg and repo-add
are the real ones, on packages made for the run with bsdtar.

Each case is a few steps (publishes one after another on the same world: the second sees what the first left). The old
program runs all steps on a fresh world, then the new one on a fresh world at the same path, and for every step these must
be the same: exit code; standard output; standard error (except the program's own last words when it stops: the script's
traceback against the port's one line; a message the script gave itself with sys.exit must be the same word for word); every
call (program, arguments, folder, the environment variables the publish sets) in order; and every file of the work folder and
of the "release" (contents and modes; the databases by the files inside them, as their archives carry the time they were
made). Two differences are intended: the release's notes name the program that made it, and the port leaves its
lock file (publish.lock, one publish at a time) in the work folder.
"""

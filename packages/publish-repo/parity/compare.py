def make_pkg(name, ver, payload, builddir="/build", deps=(), arch="x86_64", info_extra="", no_pkgname=False, sub=""):
    """A real package file (bsdtar, zstd), as makepkg lays one out: .PKGINFO, .BUILDINFO, .MTREE (gzip), the files."""
    file = os.path.join(sub, f"{name}-{ver}-{arch}.pkg.tar.zst")
    tmp = os.path.join(PKGS, ".make")
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(os.path.join(tmp, "usr", "share", "parity"))
    with open(os.path.join(tmp, "usr", "share", "parity", name), "w") as f:
        f.write(payload)
    info = "# Generated by makepkg\n" + ("" if no_pkgname else f"pkgname = {name}\n") + (
        f"pkgbase = {name}\npkgver = {ver}\npkgdesc = parity package {name}\nurl = https://example.invalid/\n"
        f"builddate = 1762992000\npackager = Parity <parity@example.invalid>\nsize = {len(payload)}\narch = {arch}\n"
        f"license = MPL-2.0\n") + "".join(f"depend = {d}\n" for d in deps) + info_extra
    with open(os.path.join(tmp, ".PKGINFO"), "w") as f:
        f.write(info)
    with open(os.path.join(tmp, ".BUILDINFO"), "w") as f:
        f.write(f"format = 2\npkgname = {name}\npkgbase = {name}\npkgver = {ver}\npkgarch = {arch}\n"
                f"packager = Parity\nbuilddate = 1762992000\nbuilddir = {builddir}\nstartdir = {builddir}\n")
    for root, dirs, files in os.walk(tmp):
        for n in dirs + files:
            os.utime(os.path.join(root, n), (1762992000, 1762992000))
    mtree = subprocess.run(["/usr/bin/bsdtar", "-cnf", "-", "--format=mtree",
                            "--options=!all,use-set,type,uid,gid,mode,time,size,sha256,link",
                            ".PKGINFO", ".BUILDINFO", "usr", "usr/share", "usr/share/parity", f"usr/share/parity/{name}"],
                           cwd=tmp, check=True, capture_output=True, env={"LANG": "C"}).stdout
    with open(os.path.join(tmp, ".MTREE"), "wb") as f:
        f.write(gzip.compress(mtree, mtime=0))
    subprocess.run(["/usr/bin/bsdtar", "--zstd", "-cf", os.path.join(PKGS, file), ".MTREE", ".PKGINFO", ".BUILDINFO", "usr"],
                   cwd=tmp, check=True)
    shutil.rmtree(tmp)
    return file



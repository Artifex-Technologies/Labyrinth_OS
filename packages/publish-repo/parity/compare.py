def snapshot(root, skip=()):
    out = {}
    for base, dirs, files in os.walk(root):
        rel_base = os.path.relpath(base, root)
        dirs[:] = sorted(d for d in dirs if os.path.normpath(os.path.join(rel_base, d)) not in skip)
        for n in sorted(files + [d for d in dirs if os.path.islink(os.path.join(base, d))]):
            p = os.path.join(base, n)
            rel = os.path.normpath(os.path.join(rel_base, n))
            st = os.lstat(p)
            if os.path.islink(p):
                out[rel] = ("link", os.readlink(p))
                continue
            data = open(p, "rb").read()
            mode = oct(st.st_mode & 0o7777)
            signed = p[:-len(".sig")]
            if n.endswith(".sig") and (".db" in n or ".files" in n) and os.path.isfile(signed):
                # the database's archive carries the time it was made, so its signature differs from run to run: what
                # must hold is that it is a good signature of the database next to it, by the test key
                ok = subprocess.run(["/usr/bin/gpg", "--batch", "--faked-system-time", "20261113T120000!", "--verify", p,
                                     signed], env={"GNUPGHOME": KEYHOME, "PATH": "/usr/bin"}, capture_output=True).returncode
                out[rel] = ("database signature", mode, "good" if ok == 0 else "bad")
                continue
            if (".db" in n or ".files" in n) and not n.endswith(".sig"):
                try:
                    with tarfile.open(fileobj=io.BytesIO(data)) as tf:
                        members = sorted((m.name, m.type.decode() if isinstance(m.type, bytes) else str(m.type),
                                          hashlib.sha256(tf.extractfile(m).read()).hexdigest() if m.isfile() else "")
                                         for m in tf.getmembers())
                    out[rel] = ("db", mode, members)
                    continue
                except tarfile.TarError:
                    pass
            out[rel] = ("file", mode, hashlib.sha256(data).hexdigest())
    return out



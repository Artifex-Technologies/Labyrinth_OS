def prepare():
    """Inside the namespace: the tmpfs world, the real keyring and gh's settings covered, no way out, a throw-away key.
    Returns the key's fingerprint."""
    real_home = os.path.expanduser("~")
    subprocess.run(["/usr/bin/mount", "-t", "tmpfs", "-o", "size=1g,mode=755", "parity", "/mnt"], check=True)
    for secret in (os.path.join(real_home, ".local", "share", "labyrinth-signing"), os.path.join(real_home, ".config", "gh")):
        if os.path.isdir(secret):
            subprocess.run(["/usr/bin/mount", "-t", "tmpfs", "-o", "size=1m,mode=700", "hidden", secret], check=True)
    with open("/proc/net/route") as f:
        routes = f.read().splitlines()[1:]
    if routes:
        sys.exit("compare.py: this namespace has a route out; refusing to run")
    os.makedirs(KEYHOME, mode=0o700)
    kenv = {"GNUPGHOME": KEYHOME, "PATH": "/usr/bin"}
    subprocess.run(["/usr/bin/gpg", "--batch", "--pinentry-mode", "loopback", "--passphrase", "", "--faked-system-time",
                    "20260101T000000!", "--quick-gen-key", "Parity throw-away key <parity@example.invalid>", "ed25519", "sign",
                    "never"], env=kenv, check=True, capture_output=True)
    listing = subprocess.run(["/usr/bin/gpg", "--batch", "--with-colons", "--list-secret-keys"], env=kenv, check=True,
                             capture_output=True, text=True).stdout
    test_key = next(l.split(":")[9] for l in listing.splitlines() if l.startswith("fpr:"))
    assert test_key != KEY
    subprocess.run(["/usr/bin/gpgconf", "--kill", "all"], env=kenv, capture_output=True)
    return test_key


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--old", default=os.path.join(REPO, "scripts", "publish-repo.py"))
    ap.add_argument("--new", default=os.path.join(CRATE, "target", "release", "labyrinth-publish-repo"))
    ap.add_argument("--only", default="")
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--inside", action="store_true", help=argparse.SUPPRESS)
    a = ap.parse_args()
    if not a.inside:
        os.execv("/usr/bin/unshare", ["unshare", "-rmnpf", "--mount-proc", "--kill-child", "--", "/usr/bin/python3", "-I",
                                      os.path.abspath(__file__), "--inside", "--old", os.path.abspath(a.old),
                                      "--new", os.path.abspath(a.new)] + (["--only", a.only] if a.only else [])
                 + (["-v"] if a.verbose else []))
    test_key = prepare()
    packages = make_packages()
    old = ["/usr/bin/python3", "-I", a.old]
    new = [a.new]
    only = set(filter(None, a.only.split(",")))
    total = same = 0
    for name, steps in CASES.items():
        if only and name not in only:
            continue
        results = {}
        for side, prog in (("old", old), ("new", new)):
            wj = new_world(packages)
            wj["test_key"] = test_key
            results[side] = [run_step(prog, s, wj, a.verbose) for s in steps]
        for i, (o, n) in enumerate(zip(results["old"], results["new"])):
            total += 1
            d = differences(o, n, name in LOOSE)
            if d:
                print(f"DIFF {name} step {i + 1}:\n  " + "\n  ".join(d))
            else:
                same += 1
                print(f"same {name} step {i + 1}: exit {o['code']}, {len(o['calls'])} calls, {len(o['files'])} files"
                      + (f", {len(o['release'])} in the release" if o["release"] is not None else ""))
    print(f"{same} of {total} steps the same")
    subprocess.run(["/usr/bin/gpgconf", "--kill", "all"], env={"GNUPGHOME": os.path.join(W, "g")}, capture_output=True)
    sys.exit(0 if same == total else 1)



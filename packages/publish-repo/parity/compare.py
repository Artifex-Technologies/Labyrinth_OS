NOTES = ("Filled by scripts/publish-repo.py.", "Filled by labyrinth-publish-repo (packages/publish-repo).")


def run_step(prog, step, wj, verbose):
    wj["step"] = step
    for f in os.listdir(W):
        if f.startswith("count-") or f == "calls.jsonl":
            os.unlink(os.path.join(W, f))
    with open(os.path.join(W, "world.json"), "w") as f:
        json.dump(wj, f)
    templates(step["sources"])
    if "state" in step:
        os.makedirs(os.path.join(W, "work"), exist_ok=True)
        with open(os.path.join(W, "work", "published.json"), "w") as f:
            f.write(step["state"])
    env = {"PATH": os.path.join(W, "bin"), "HOME": os.path.join(W, "home"), "LANG": "C.UTF-8", "TZ": "UTC",
           "LABYRINTH_PUBLISH_DIR": os.path.join(W, "work"), "PARITY_WORLD": W,
           "LABYRINTH_GNUPGHOME": os.path.join(W, step.get("gnupg", "g")),
           # both must override what the caller's environment says
           "LABYRINTH_SKIP": "labyrinth-tools"}
    p = subprocess.run(prog + step.get("args", []), env=env, cwd=os.path.join(W, "home"), capture_output=True, timeout=300)
    calls = []
    if os.path.exists(os.path.join(W, "calls.jsonl")):
        for line in open(os.path.join(W, "calls.jsonl")):
            c = json.loads(line)
            c["argv"] = [a.replace(NOTES[0], "<notes>").replace(NOTES[1], "<notes>") for a in c["argv"]]
            calls.append(c)
    files = snapshot(os.path.join(W, "work"), skip={os.path.join("src", n, ".git") for n in
                                                   ("Labyrinth_OS", "Yggdrasil", "Sarina", "Heimdall", "Limbo")})
    # the port's lock file (one publish at a time; the script had none): an intended difference, left out
    files.pop("publish.lock", None)
    release = snapshot(os.path.join(W, "release")) if os.path.isdir(os.path.join(W, "release")) else None
    if verbose:
        sys.stderr.write(f"--- {prog[-1]} {step.get('args', [])}: exit {p.returncode}\n{p.stdout.decode(errors='replace')}"
                         f"{p.stderr.decode(errors='replace')}")
    return {"code": p.returncode, "stdout": p.stdout.decode(errors="replace"), "stderr": p.stderr.decode(errors="replace"),
            "calls": calls, "files": files, "release": release}


def own_name(text):
    return text.replace("labyrinth-publish-repo", "<prog>").replace("publish-repo.py", "<prog>")


def own_last_words(err, code):
    """Standard error without the program's own report of why it stopped: the script's traceback, the port's last line."""
    if "Traceback (most recent call last):" in err:
        return err.split("Traceback (most recent call last):")[0], "traceback"
    lines = err.splitlines(keepends=True)
    if code == 1 and lines and lines[-1].startswith("error: "):
        return "".join(lines[:-1]), lines[-1]
    return err, None


def differences(old, new, loose):
    d = []
    if old["code"] != new["code"]:
        d.append(f"exit code {old['code']} != {new['code']}")
    if loose:
        return d
    if own_name(old["stdout"]) != own_name(new["stdout"]):
        d.append(f"stdout:\n  old: {old['stdout']!r}\n  new: {new['stdout']!r}")
    (oe, ow), (ne, nw) = (own_last_words(own_name(old["stderr"]), old["code"]),
                          own_last_words(own_name(new["stderr"]), new["code"]))
    if oe != ne:
        d.append(f"stderr:\n  old: {oe!r}\n  new: {ne!r}")
    if (ow is None) != (nw is None) or (ow not in (None, "traceback") and ow != nw):
        d.append(f"last words: {ow!r} != {nw!r}")
    if old["calls"] != new["calls"]:
        n = next((i for i, (a, b) in enumerate(zip(old["calls"], new["calls"])) if a != b), min(len(old["calls"]), len(new["calls"])))
        d.append(f"calls differ at #{n} ({len(old['calls'])} against {len(new['calls'])}):\n  old: "
                 f"{old['calls'][n] if n < len(old['calls']) else None}\n  new: {new['calls'][n] if n < len(new['calls']) else None}")
    for what in ("files", "release"):
        a, b = old[what], new[what]
        if a != b:
            if a is None or b is None:
                d.append(f"{what}: {a is None} / {b is None}")
                continue
            for k in sorted(set(a) | set(b)):
                if a.get(k) != b.get(k):
                    d.append(f"{what} {k}: {a.get(k)} != {b.get(k)}")
    return d


